"""Bit layouts for RTCM station, observation and broadcast ephemeris data."""

from dataclasses import dataclass
from types import MappingProxyType


@dataclass(frozen=True, slots=True)
class BitField:
    code: int | str
    bits: int
    scale: float = 1
    sign_magnitude: bool = False

    @property
    def name(self) -> str:
        return f"DF{self.code:03}" if isinstance(self.code, int) else self.code


